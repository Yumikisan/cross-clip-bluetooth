/**
 * Two-language resource table (English / Simplified Chinese).
 *
 * The active language lives in a [StateFlow] so switching it recomposes the whole UI
 * without recreating the activity.
 */
object I18n {
    const val SYSTEM = "system"
    const val EN = "en"
    const val ZH = "zh"

    private val _language = MutableStateFlow(ZH)
    val language: StateFlow<String> = _language.asStateFlow()

    fun resolve(setting: String): String = when (setting) {
        EN -> EN
        ZH -> ZH
        else -> if (Locale.getDefault().language.startsWith("zh")) ZH else EN
    }

    fun apply(setting: String) {
        _language.value = resolve(setting)
    }

    fun isChinese(): Boolean = _language.value == ZH

    fun t(key: String, vararg args: Any): String {
        val table = if (_language.value == ZH) ZH_MAP else EN_MAP
        val template = table[key] ?: EN_MAP[key] ?: key
        return if (args.isEmpty()) template else runCatching { String.format(template, *args) }.getOrDefault(template)
    }

