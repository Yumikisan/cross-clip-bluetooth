/**
 * First-run security wizard. Explains why there is a second encryption layer on top of the
 * Bluetooth pairing, then offers the three ways to obtain a pre-shared key: generate one, type in
 * one that already exists, or invent your own.
 *
 * Deliberately dismissible. A key configured on one device only makes that device refuse plaintext
 * peers, which looks exactly like a broken connection — refusing to let the user in until a key
 * exists would be worse than the plaintext default.
 */
@Composable
fun SecurityWizardDialog(
    settingsViewModel: SettingsViewModel,
    onDismiss: () -> Unit,
) {
    val clipboard = LocalClipboardManager.current

    // 0 = intro, 1 = generated key, 2 = paste an existing one, 3 = invent one
    var step by remember { mutableStateOf(0) }
    var generated by remember { mutableStateOf("") }
    var draft by remember { mutableStateOf("") }
    var error by remember { mutableStateOf<String?>(null) }
    var copied by remember { mutableStateOf(false) }

    // t() is @Composable, so it is resolved here and captured by the plain click lambda below.
    val tooShortMessage = t("wiz_need_len", SecurityPolicy.MIN_PASSPHRASE_LENGTH)
    val storeFailedMessage = t("wiz_store_failed")

    val finish: () -> Unit = {
        val key = if (step == 1) generated else draft
        val normalised = SecurityPolicy.normalize(key)
        when {
            normalised.isEmpty() -> step = 0
            normalised.length < SecurityPolicy.MIN_PASSPHRASE_LENGTH -> error = tooShortMessage
            else -> {
                val failure = settingsViewModel.setPsk(normalised)
                if (failure == null) onDismiss() else error = storeFailedMessage
            }
        }
    }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = {
            Text(
                t(if (step == 0) "wiz_headline" else "wiz_title"),
                fontSize = 16.sp,
                fontWeight = FontWeight.SemiBold
            )
        },
        text = {
            Column(modifier = Modifier.heightIn(max = 460.dp).verticalScroll(rememberScrollState())) {
                when (step) {
                    0 -> {
                        Body(t("wiz_intro1"))
                        Body(t("wiz_intro2"))
                        Body(t("wiz_intro3"))
                        Spacer8()
                        OptionRow(Icons.Filled.Shield, t("wiz_opt_generate"), t("wiz_opt_generate_hint")) {
                            generated = PskGenerator.generate()
                            error = null
                            copied = false
                            step = 1
                        }
                        OptionRow(Icons.Filled.Key, t("wiz_opt_existing"), t("wiz_opt_existing_hint")) {
                            draft = ""
                            error = null
                            step = 2
                        }
                        OptionRow(Icons.Filled.Lock, t("wiz_opt_create"), t("wiz_opt_create_hint")) {
                            draft = ""
                            error = null
                            step = 3
                        }
                    }

                    1 -> {
                        Body(t("wiz_generated_hint"))
                        Text(
                            generated,
                            fontFamily = FontFamily.Monospace,
                            fontSize = 19.sp,
                            fontWeight = FontWeight.SemiBold,
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(vertical = 12.dp)
                        )
                        Row(
                            horizontalArrangement = Arrangement.spacedBy(8.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            OutlinedButton(onClick = {
                                clipboard.setText(AnnotatedString(generated))
                                // The key must not be carried over the link it protects: mark it
                                // as already seen so the clipboard capture skips it.
                                BluetoothService.instance?.suppressClipboardEcho(generated)
                                copied = true
                            }) {
                                Icon(Icons.Filled.ContentCopy, contentDescription = null, modifier = Modifier.padding(end = 6.dp))
                                Text(t("wiz_copy"), fontSize = 12.sp)
                            }
                            if (copied) Text(t("wiz_copied"), fontSize = 11.sp, color = MaterialTheme.colorScheme.primary)
                        }
                        Fingerprint(generated)
                    }

                    else -> {
                        Body(t(if (step == 2) "wiz_existing_hint" else "wiz_create_hint"))
                        OutlinedTextField(
                            value = draft,
                            onValueChange = { draft = it; error = null },
                            singleLine = true,
                            label = { Text(t("wiz_key_label"), fontSize = 12.sp) },
                            textStyle = MaterialTheme.typography.bodyMedium.copy(fontFamily = FontFamily.Monospace),
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                            modifier = Modifier.fillMaxWidth().padding(top = 8.dp)
                        )
                        if (step == 3) {
                            TextButton(onClick = { draft = PskGenerator.generate(); error = null }) {
                                Text(t("wiz_suggest"), fontSize = 12.sp)
                            }
                        }
                        Fingerprint(draft)
                    }
                }

                error?.let {
                    Text(
                        it,
                        fontSize = 11.sp,
                        color = MaterialTheme.colorScheme.error,
                        modifier = Modifier.padding(top = 8.dp)
                    )
                }

            }
        },
        confirmButton = {
            when (step) {
                0 -> TextButton(onClick = onDismiss) { Text(t("wiz_later")) }
                else -> TextButton(onClick = { finish() }) { Text(t("wiz_finish")) }
            }
        },
        dismissButton = {
            if (step != 0) {
                TextButton(onClick = { step = 0; error = null }) { Text(t("wiz_back")) }
            }
        }
    )
}

@Composable
private fun Body(text: String) {
    Text(
        text,
        fontSize = 12.sp,
        lineHeight = 18.sp,
        color = MaterialTheme.colorScheme.onSurfaceVariant,
        modifier = Modifier.padding(top = 6.dp)
    )
}

@Composable
private fun Spacer8() {
    Text("", fontSize = 2.sp)
}

@Composable
private fun Fingerprint(key: String) {
    val normalised = SecurityPolicy.normalize(key)
    if (normalised.length < SecurityPolicy.MIN_PASSPHRASE_LENGTH) return
    Text(
        t("wiz_fingerprint", PskVault.fingerprint(normalised)),
        fontSize = 11.sp,
        color = MaterialTheme.colorScheme.primary,
        modifier = Modifier.padding(top = 10.dp)
    )
}

@Composable
private fun OptionRow(icon: ImageVector, title: String, hint: String, onClick: () -> Unit) {
    OutlinedButton(
        onClick = onClick,
        modifier = Modifier.fillMaxWidth().padding(top = 8.dp)
    ) {
        Column(modifier = Modifier.fillMaxWidth().padding(vertical = 6.dp)) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(icon, contentDescription = null, modifier = Modifier.padding(end = 8.dp))
                Text(title, fontSize = 13.sp, fontWeight = FontWeight.SemiBold)
            }
            Text(hint, fontSize = 11.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
    }
}
